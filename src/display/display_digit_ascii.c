void draw_ascii_digit(int digit, int start_x, int start_y)
{
    const char *g_ascii_numbers[10][5] = {
    {" ### ",
     "#   #",
     "#   #",
     "#   #",
     " ### "},
    
    {"  #  ",
     " ##  ",
     "  #  ",
     "  #  ",
     " ### "},
    
    {" ### ",
     "#   #",
     "   # ",
     "  #  ",
     "#####"},
    
    {" ### ",
     "    #",
     "  ## ",
     "    #",
     " ### "},
    
    {"   # ",
     "  ## ",
     " # # ",
     "#####",
     "   # "},
    
    {"#####",
     "#    ",
     "#### ",
     "    #",
     "#### "},
    
    {" ### ",
     "#    ",
     "#### ",
     "#   #",
     " ### "},
    
    {"#####",
     "    #",
     "   # ",
     "  #  ",
     "  #  "},
    
    {" ### ",
     "#   #",
     " ### ",
     "#   #",
     " ### "},
    
    {" ### ",
     "#   #",
     " ####",
     "    #",
     " ### "}
    };
    if (digit < 0 || digit > 9)
        return;

    int i = 0;
    while (i < 5)
    {
        mvprintw(start_y + i, start_x, "%s", g_ascii_numbers[digit][i]);
        i++;
    }
}